"""
Final configuration for the official submission (Assignment 3, E8).

The official submission (January 2027) trains Stage B on all 10 Swedish
words, so there is no validation word left to choose the number of epochs,
the clustering cut t, the minimum cluster size m or the Subtask 2 threshold
tau. Each of them is fixed here to its median over the 50 folds of the five
seed runs of the main system (5 seeds x 10 folds). Only choices that were
made WITHOUT the test word of each fold enter the medians, so no test score
is used.

    python -m src.final_config                  # writes configs/final.yaml and
                                                # results/summary/final_config.json

configs/final.yaml = configs/default.yaml with
  * training.stage_a_guard: true  (keep the pre-training weights if Stage A
    lowers the held-out synthetic pair AUC; see DEVIATIONS.md, seed 87)
  * a 'final:' block with the four fixed values and where they come from.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

MAIN_SYSTEM = 'proposed_ft_syn_sv'
SEEDS = (13, 42, 87, 1234, 2027)
RUN_NAME = re.compile(r'^\d{8}-\d{6}_(?P<system>.+)_seed(?P<seed>\d+)$')


def main_runs(runs_dir, system=MAIN_SYSTEM, seeds=SEEDS):
    """Latest run folder of `system` for every seed (error if one is missing)."""
    found = {}
    for d in sorted(Path(runs_dir).iterdir()):
        m = RUN_NAME.match(d.name)
        if m and m['system'] == system and int(m['seed']) in seeds and (d / 'scores.json').exists():
            found[int(m['seed'])] = d                  # sorted by time: the latest wins
    missing = [s for s in seeds if s not in found]
    if missing:
        raise FileNotFoundError(f'No finished {system} run for seed(s) {missing} in {runs_dir}')
    return [found[s] for s in seeds]


def fold_choices(run_dir, split_file=REPO_ROOT / 'data' / 'splits' / 'SV_splits.json'):
    """Per fold: best Stage B epoch, t, m and tau (all chosen without the test word)."""
    hist = json.loads((run_dir / 'training_history.json').read_text(encoding='utf-8'))
    sel = json.loads((run_dir / 'selection.json').read_text(encoding='utf-8'))['per_test_word']
    folds = json.loads(Path(split_file).read_text(encoding='utf-8'))['folds']
    rows = []
    for f in folds:
        word = f['test'][0]
        best = [e['epoch'] for e in hist[f"fold{f['fold']}"] if e.get('best')]
        c = sel[word]
        rows.append({'fold': f['fold'], 'test_word': word, 'best_epoch': best[0],
                     't': c['clustering']['threshold'], 'm': c['clustering']['min_size'],
                     'tau': c['subtask2']['absolute_threshold']})
    return rows


def medians(runs):
    rows = []
    for d in runs:
        seed = int(RUN_NAME.match(d.name)['seed'])
        rows += [{'seed': seed, **r} for r in fold_choices(d)]
    col = lambda k: np.array([r[k] for r in rows], dtype=float)  # noqa: E731
    return {
        'stage_b_epochs': int(np.median(col('best_epoch'))),
        'cluster_threshold': round(float(np.median(col('t'))), 4),
        'min_cluster_size': int(np.median(col('m'))),
        'subtask2_threshold': round(float(np.median(col('tau'))), 4),
    }, rows


def write_final_yaml(values, runs, default=REPO_ROOT / 'configs' / 'default.yaml',
                     out=REPO_ROOT / 'configs' / 'final.yaml'):
    text = Path(default).read_text(encoding='utf-8')
    old = re.search(r'^  stage_a_guard: false[^\n]*$', text, flags=re.M)
    if not old:
        raise ValueError('training.stage_a_guard not found in the default config')
    text = text.replace(old.group(0), '  stage_a_guard: true                       '
                                      '# on for the submission (see DEVIATIONS.md, seed 87)')
    header = ('# =====================================================================\n'
              '# FINAL configuration for the official submission (E8).\n'
              '# Generated by: python -m src.final_config  (do not edit by hand)\n'
              '# = configs/default.yaml + training.stage_a_guard: true + the final: block.\n'
              '# =====================================================================\n')
    block = ('\n# --- E8: values fixed for the submission (Stage B on all 10 Swedish words) ---\n'
             '# Medians over 50 folds (5 seeds x 10 folds); every value was chosen without\n'
             '# the test word of its fold. Per-fold values: results/summary/final_config.json\n'
             'final:\n'
             f"  stage_b_epochs: {values['stage_b_epochs']}                         "
             '# median best Stage B epoch (0 = Stage A weights)\n'
             f"  cluster_threshold: {values['cluster_threshold']}                 "
             '# median cut t (cosine distance)\n'
             f"  min_cluster_size: {values['min_cluster_size']}                      "
             '# median minimum cluster size m\n'
             f"  subtask2_threshold: {values['subtask2_threshold']}                "
             '# median absolute cosine threshold tau\n'
             '  source_runs:\n' + ''.join(f'    - {d.name}\n' for d in runs))
    Path(out).write_text(header + text.rstrip('\n') + '\n' + block, encoding='utf-8')
    return Path(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description='Fix the final configuration (E8) from the five seed runs.')
    ap.add_argument('--runs', default=str(REPO_ROOT / 'results' / 'runs'))
    ap.add_argument('--out', default=str(REPO_ROOT / 'configs' / 'final.yaml'))
    ap.add_argument('--record', default=str(REPO_ROOT / 'results' / 'summary' / 'final_config.json'))
    a = ap.parse_args(argv)
    runs = main_runs(a.runs)
    values, rows = medians(runs)
    out = write_final_yaml(values, runs, out=a.out)
    Path(a.record).parent.mkdir(parents=True, exist_ok=True)
    Path(a.record).write_text(json.dumps({'values': values, 'runs': [d.name for d in runs],
                                          'per_fold': rows}, indent=2), encoding='utf-8')
    print(json.dumps(values, indent=2))
    print(f'Saved: {out} and {a.record}')


if __name__ == '__main__':
    main()
